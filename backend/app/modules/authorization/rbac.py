def has_organization_permission(
    role: OrganizationRole | None, permission: OrganizationPermission
) -> bool:
    if role is None:
        return False
    return permission in ORG_ROLE_PERMISSIONS.get(role, set())


def has_workspace_permission(
    org_role: OrganizationRole | None,
    ws_role: WorkspaceRole | None,
    permission: WorkspacePermission,
) -> bool:
    # 1. Organization Owner inherits full control over all child workspaces
    if org_role == OrganizationRole.OWNER:
        return True

    # 2. Check workspace role permissions
    if ws_role is not None and permission in WORKSPACE_ROLE_PERMISSIONS.get(ws_role, set()):
        return True

    return False
